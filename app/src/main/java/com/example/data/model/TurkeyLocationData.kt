  fun normalizeTurkish(input: String): String {
    return input.lowercase(java.util.Locale("tr", "TR"))
      .replace('ı', 'i')
      .replace('ğ', 'g')
      .replace('ü', 'u')
      .replace('ş', 's')
      .replace('ö', 'o')
      .replace('ç', 'c')
      .replace("i̇", "i")
  }

  fun getProvinceByName(name: String): ProvinceInfo? {
    val clean = normalizeTurkish(name.trim())
    return PROVINCES.find { normalizeTurkish(it.name) == clean || it.name.equals(name, ignoreCase = true) }
  }

  fun getDistrictByName(provinceName: String, districtName: String): DistrictInfo? {
    val province = getProvinceByName(provinceName) ?: return null
    val cleanDist = normalizeTurkish(districtName.trim())
    return province.districts.find { normalizeTurkish(it.name) == cleanDist || it.name.equals(districtName, ignoreCase = true) }
  }

  fun searchProvinces(query: String): List<ProvinceInfo> {
    val cleanQuery = normalizeTurkish(query.trim())
    if (cleanQuery.isBlank()) return PROVINCES
    return PROVINCES.filter {
      normalizeTurkish(it.name).contains(cleanQuery) ||
        it.plateCode.toString().startsWith(cleanQuery)
    }
  }

  fun searchDistricts(provinceName: String, query: String): List<DistrictInfo> {
    val province = getProvinceByName(provinceName) ?: return emptyList()
    val cleanQuery = normalizeTurkish(query.trim())
    if (cleanQuery.isBlank()) return province.districts
    return province.districts.filter {
      normalizeTurkish(it.name).contains(cleanQuery)
    }
  }
